# DTO (Data Transfer Object, объект передачи данных) — это объект,
# предназначенный для передачи данных между частями системы.
# Он описывает структуру передаваемых данных, но обычно не содержит
# бизнес-логики.
# В классическом определении DTO использовался для передачи сразу набора
# данных между процессами или удалёнными компонентами, чтобы не делать
# множество отдельных вызовов. В современных приложениях DTO часто применяют
# и внутри одного процесса — например, между ETL-этапами, API, сервисом
# и репозиторием.

